"""Translates the UPX unpacker stub of a packed game exe (GOG ships pop2.exe / pop3.exe packed) into C, so the app
can run the exe as installed: the stub decompresses the game into the UPX0 section, fills the import table through
LoadLibraryA/GetProcAddress and jumps to the original entry point, which is translated code (out_all/).

The stub is the exe's own code and runs translated like the rest of the game; this project ships no UPX/UCL code.
Its range is entry .. the final `jmp <original entry point>`. Writes one C file with
    f_<stub>(CPU *)              the translated stub
    register_upx_stub()          registers it
    upx_stub_entry, upx_oep      where it starts and where it hands over to the game
    upx_check[], upx_check_hash  address ranges of the unpacked exe's code and data (.text/.rdata/.data, without
                                 the import table, which the loader and the stub fill differently) and their
                                 FNV-1a hash: the app compares what the stub produced with the exe the game was
                                 translated from

usage: python -I upx_stub.py <packed.exe> <unpacked.exe> <out.c>
       python -I upx_stub.py --none <out.c>      (no packed exe at hand: packed exes are then refused at start)"""
import json, os, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "translator"))


def none_file(out):
    with open(out, "w") as f:
        f.write('#include "runtime.h"\n/* generated by tools/upx_stub.py --none: no packed exe was available */\n'
                "const uint32_t upx_stub_entry = 0, upx_oep = 0;\n"
                "const uint32_t upx_check[][2] = { { 0, 0 } }, upx_ncheck = 0;\n"
                "const uint64_t upx_check_hash = 0;\n"
                "void register_upx_stub(void) {}\n")


def check_ranges(unpacked):
    """[lo, hi) ranges of the unpacked image to compare, and the FNV-1a 64 hash of their bytes as mapped"""
    import pefile
    up = pefile.PE(unpacked, fast_load=True)
    up.parse_data_directories(directories=[1])
    base = up.OPTIONAL_HEADER.ImageBase
    img = up.get_memory_mapped_image()
    skip = set()   # import descriptors, lookup tables, names and the IAT: rebuilt by `upx -d`, filled by the loader
    d = up.OPTIONAL_HEADER.DATA_DIRECTORY[1]
    skip.update(range(d.VirtualAddress, d.VirtualAddress + 20 * (len(up.DIRECTORY_ENTRY_IMPORT) + 1)))
    for e in up.DIRECTORY_ENTRY_IMPORT:
        skip.update(range(e.struct.Name, e.struct.Name + len(e.dll) + 1))
        for k, i in enumerate(e.imports):
            for t in filter(None, (e.struct.OriginalFirstThunk, e.struct.FirstThunk)):
                skip.update(range(t + 4 * k, t + 4 * k + 8))   # this slot and the list's 0 terminator
            if i.name:
                skip.update(range(i.hint_name_table_rva, i.hint_name_table_rva + 2 + len(i.name) + 2))
    ranges = []
    for sec in up.sections:
        if sec.Name.rstrip(b"\0") not in (b".text", b".rdata", b".data"):
            continue   # .rsrc (the app reads no resources) and T2T's .start (the import table `upx -d` rebuilt)
        lo, hi = sec.VirtualAddress, sec.VirtualAddress + sec.Misc_VirtualSize
        a = lo
        while a < hi:
            while a < hi and a in skip:
                a += 1
            b = a
            while b < hi and b not in skip:
                b += 1
            if b > a:
                ranges.append((a, b))
            a = b
    h = 0xcbf29ce484222325
    for a, b in ranges:
        chunk = bytes(img[a:b]) + bytes(max(0, b - max(a, len(img))))
        for x in chunk:
            h = ((h ^ x) * 0x100000001b3) & 0xffffffffffffffff
    return [(base + a, base + b) for a, b in ranges], h


def main():
    if sys.argv[1] == "--none":
        return none_file(sys.argv[2])
    exe, unpacked, out = sys.argv[1], sys.argv[2], sys.argv[3]
    import pefile
    from capstone import Cs, CS_ARCH_X86, CS_MODE_32
    import x86toc

    pe = pefile.PE(exe, fast_load=True)
    base = pe.OPTIONAL_HEADER.ImageBase
    img = pe.get_memory_mapped_image()
    secs = {s.Name.rstrip(b"\0").decode("latin1"): (base + s.VirtualAddress, base + s.VirtualAddress + s.Misc_VirtualSize)
            for s in pe.sections}
    assert "UPX0" in secs and "UPX1" in secs, "%s is not UPX-packed (sections %s)" % (exe, list(secs))
    entry = base + pe.OPTIONAL_HEADER.AddressOfEntryPoint
    lo, hi = secs["UPX1"]
    assert lo <= entry < hi, "entry %08x is not in UPX1" % entry

    # the stub runs straight through to `jmp <OEP>`, the first direct jump that leaves UPX1
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    end = oep = None
    for ins in md.disasm(img[entry - base: hi - base], entry):
        if ins.mnemonic == "jmp" and ins.op_str.startswith("0x"):
            t = int(ins.op_str, 16)
            if not lo <= t < hi:
                end, oep = ins.address + ins.size, t
                break
    assert oep and secs["UPX0"][0] <= oep < secs["UPX0"][1], "no jump from the stub into UPX0"
    up = pefile.PE(unpacked, fast_load=True)
    assert up.OPTIONAL_HEADER.ImageBase + up.OPTIONAL_HEADER.AddressOfEntryPoint == oep, \
        "%s does not start at the stub's original entry point %08x" % (unpacked, oep)

    # The translator scans .text/.rdata/.data for code pointers; a packed exe has none of those sections.
    x86toc.Program.add_pointer_entries = lambda self, pe: None
    with tempfile.TemporaryDirectory() as tmp:
        fj = os.path.join(tmp, "functions.json")
        with open(fj, "w") as f:
            json.dump({"functions": [{"entry": entry, "name": "upx_stub", "cc": "unknown", "purge": 0,
                                      "ranges": [[entry, end]]}], "jumptables": []}, f)
        prog = x86toc.Program(exe, fj)
        src, unsupported, n = x86toc.FunctionTranslator(prog, prog.functions[entry]).translate()
    if unsupported:
        sys.exit("unsupported instructions in the stub: %s" % unsupported)
    ranges, h = check_ranges(unpacked)
    with open(out, "w") as f:
        f.write("/* generated by tools/upx_stub.py from %s: the exe's own UPX unpacker stub, %d instructions */\n"
                % (os.path.basename(exe), n))
        f.write('#include "runtime.h"\n#include "simd.h"\n#include <math.h>\n\n')
        f.write("void f_%08x(CPU *c);\n" % entry)
        f.write(src)
        f.write("\nconst uint32_t upx_stub_entry = 0x%08xu, upx_oep = 0x%08xu;\n" % (entry, oep))
        f.write("const uint32_t upx_check[][2] = {\n")
        f.write("".join("    { 0x%08xu, 0x%08xu },\n" % r for r in ranges))
        f.write("};\nconst uint32_t upx_ncheck = %d;\n" % len(ranges))
        f.write("const uint64_t upx_check_hash = 0x%016xull;   /* FNV-1a 64 of upx_check in %s */\n"
                % (h, os.path.basename(unpacked)))
        f.write("void register_upx_stub(void) { register_function(0x%08xu, f_%08x); }\n" % (entry, entry))
    print("upx stub %08x-%08x (%d instructions) -> original entry %08x, %d check ranges: %s"
          % (entry, end, n, oep, len(ranges), out))


if __name__ == "__main__":
    main()
